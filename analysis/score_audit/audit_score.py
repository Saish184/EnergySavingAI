"""Audit a sustainability-score implementation against the mathematical requirements.

  python analysis/score_audit/audit_score.py              # harness self-test on fixtures (always available)
  python analysis/score_audit/audit_score.py --teammate   # audit the teammate's score.py (once wrap() is written)

Writes reports/score_audit.json and reports/score_audit.md. Reproduces scores for all 8 flats, runs every
invariant, and runs a weight-sensitivity sweep when the model declares weights.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import REPORTS  # noqa: E402
from mathcore import load_flats  # noqa: E402
import fixtures as fx  # noqa: E402
import invariants as inv  # noqa: E402
import teammate_adapter  # noqa: E402


def fixture_models():
    e, t = fx.EnergyTotalFixture(), fx.WholeFlatPriceRatioFixture()
    return [e, t, fx.CoverageAdjustedEnergyFixture(), fx.PeerRelativeUnfrozenFixture(),
            fx.CompositeFixture({"energy": e, "timing": t}, {"energy": 0.6, "timing": 0.4}, "arithmetic"),
            fx.CompositeFixture({"energy": e, "timing": t}, {"energy": 0.6, "timing": 0.4}, "geometric"),
            fx.CompositeFixture({"energy": e, "timing": t}, {"energy": 0.6, "timing": 0.4}, "geometric", floor=1.0)]


def weight_sensitivity(model, flats, refs, steps=(-0.10, 0.10)):
    """Perturb each weight by +/-10 % (renormalised) and report rank changes. Needs model.with_weights()."""
    if not model.pillar_weights or not hasattr(model, "with_weights"):
        return None
    base = model.score(flats, refs)
    rank = lambda s: [fl for fl, _ in sorted(s.items(), key=lambda kv: -kv[1]["score"])]
    r0, out = rank(base), []
    for k in model.pillar_weights:
        for st in steps:
            w = dict(model.pillar_weights); w[k] *= 1 + st
            tot = sum(w.values()); w = {a: b / tot for a, b in w.items()}
            r1 = rank(model.with_weights(w).score(flats, refs))
            out.append({"pillar": k, "change": st, "rank": r1, "rank_changed": r1 != r0})
    return {"baseline_rank": r0, "perturbations": out}


def audit(model, flats):
    refs = model.fit_references(flats)
    scores = model.score(flats, refs)
    results = inv.run_all(model, flats)
    return {"model": model.name, "aggregation": model.aggregation, "weights": model.pillar_weights,
            "scores": {fl: {"score": round(v["score"], 4), "pillars": {k: round(p, 4) for k, p in v["pillars"].items()}} for fl, v in scores.items()},
            "summary": inv.summary(results), "results": results, "weight_sensitivity": weight_sensitivity(model, flats, refs)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--teammate", action="store_true")
    a = ap.parse_args()
    flats = load_flats()
    report = {"teammate_model": None, "teammate_status": None, "fixtures": []}
    try:
        tm = teammate_adapter.load()
        report["teammate_status"] = "loaded"
        if a.teammate:
            report["teammate_model"] = audit(tm, flats)
    except teammate_adapter.Unavailable as e:
        report["teammate_status"] = f"UNAVAILABLE: {e}"
    report["documented_method_not_verified"] = teammate_adapter.DOCUMENTED_METHOD
    for m in fixture_models():
        report["fixtures"].append(audit(m, flats))
    (REPORTS / "score_audit.json").write_text(json.dumps(report, indent=2, default=str) + "\n")

    md = ["# Score audit", "", "_Generated by `analysis/score_audit/audit_score.py`._", "",
          f"**Teammate implementation:** {report['teammate_status']}", "",
          "Without the teammate's code, this report contains **no verification of the four-pillar model**. "
          "The fixtures below are deliberately simple test doubles. They exist only to prove that each check detects the "
          "behaviour it targets; they are not proposals.", ""]
    for m in ([report["teammate_model"]] if report["teammate_model"] else []) + report["fixtures"]:
        s = m["summary"]
        md += [f"## {m['model']}", "",
               f"Universal: {s['universal']['checks'] - s['universal']['failed']}/{s['universal']['checks']} pass · "
               f"policy: {s['policy']['failed']} inconsistent · heuristic flags: {s['heuristic']['failed']}", "",
               "| Requirement | Class | Check | Case | Result | Detail |", "|---|---|---|---|---|---|"]
        for r in m["results"]:
            if r["passed"] is False or r["cls"] in ("info",) or r["check"] in ("determinism", "peer invariance under frozen references"):
                res = {True: "pass", False: "**FAIL**", None: "info"}[r["passed"]]
                md.append(f"| {r['requirement']} | {r['cls']} | {r['check']} | {r['case']} | {res} | {str(r['detail'])[:120]} |")
        md.append("")
    (REPORTS / "score_audit.md").write_text("\n".join(md))
    for m in report["fixtures"]:
        print(m["model"], m["summary"])
    print("teammate:", report["teammate_status"])


if __name__ == "__main__":
    main()
