"""Load hourly data into a Dataset of FlatData.

Sources, in order (FEC_DATA_SOURCE=auto):
  1. data/processed/analytical_table.csv  - the validated pipeline output (analysis/clean_data.py): readings,
     occupancy, weather, prices and carbon already cleaned, joined and DST-checked.
  2. data/processed/clean_readings.csv    - the original backend data contract (long readings), joined here to
     the organiser context/prices with validity guards.
  3. data/mock/                           - synthetic stand-in generated by mock_data.py.
This module only parses and guards; it never turns invalid values into zeros (they become NaN = unknown).
Anomalies are NOT read from files any more: the engine detects them (core/detect.py)."""
from __future__ import annotations

import numpy as np
import pandas as pd

from . import config as C
from .core.dataset import Dataset
from .core.hourly import flats_from_frames


def parse_utc(s: pd.Series) -> pd.Series:
    """ISO UTC, plus the legacy 'YYYY/MM/DD HH:MM' export (also UTC)."""
    out = pd.to_datetime(s, utc=True, errors="coerce", format="ISO8601")
    bad = out.isna() & s.notna()
    if bad.any():
        out[bad] = pd.to_datetime(s[bad], utc=True, errors="coerce", format="%Y/%m/%d %H:%M")
    return out


def _in_period(df: pd.DataFrame) -> pd.DataFrame:
    start, end = pd.Timestamp(C.PERIOD_START), pd.Timestamp(C.PERIOD_END)
    return df[(df["timestamp_utc"] >= start) & (df["timestamp_utc"] < end)]


def resolve_source() -> tuple[str, str]:
    table = C.PROCESSED_DIR / "analytical_table.csv"
    long = C.PROCESSED_DIR / "clean_readings.csv"
    if C.DATA_SOURCE == "mock":
        return "mock", str(C.MOCK_DIR)
    if table.exists():
        return "processed", str(table)
    if long.exists():
        return "processed_contract", str(long)
    if C.DATA_SOURCE == "processed":
        raise FileNotFoundError("no processed data: run `make pipeline` (analysis/clean_data.py)")
    return "mock", str(C.MOCK_DIR)


def load_flats() -> pd.DataFrame:
    f = pd.read_csv(C.RAW_DIR / "flats.csv", dtype={"flat_id": str})
    f["residents"] = pd.to_numeric(f["residents"], errors="coerce")
    f["floor_area_m2"] = pd.to_numeric(f["floor_area_m2"], errors="coerce")
    return f


def load_prices(quality: dict) -> pd.DataFrame:
    p = pd.read_csv(C.RAW_DIR / "hourly_prices.csv", dtype=str)
    p["timestamp_utc"] = parse_utc(p["timestamp_utc"])
    p["spot"] = pd.to_numeric(p["spot_sek_per_kwh"], errors="coerce")          # negative prices are valid
    p["carbon"] = pd.to_numeric(p["carbon_gco2e_per_kwh"], errors="coerce")
    p.loc[p["carbon"] < 0, "carbon"] = np.nan
    n = len(p)
    p = p.drop_duplicates(subset=["timestamp_utc", "price_area"], keep="first")
    quality["prices_missing_spot_hours"] = int(p["spot"].isna().sum())
    quality["prices_duplicates_dropped"] = n - len(p)
    return _in_period(p[["timestamp_utc", "price_area", "spot", "carbon"]])


def load_context(flats: pd.DataFrame, quality: dict) -> pd.DataFrame:
    c = pd.read_csv(C.RAW_DIR / "hourly_context.csv", dtype=str)
    c["timestamp_utc"] = parse_utc(c["timestamp_utc"])
    for col in ("occupants_home", "indoor_temp_c", "outdoor_temp_c"):
        c[col] = pd.to_numeric(c[col], errors="coerce")
    res = c["flat_id"].map(flats.set_index("flat_id")["residents"])
    impossible = (c["occupants_home"] < 0) | (c["occupants_home"] > res)
    quality["context_occupancy_missing"] = int(c["occupants_home"].isna().sum())
    quality["context_occupancy_impossible_to_unknown"] = int(impossible.sum())
    c.loc[impossible, "occupants_home"] = np.nan                              # unknown, NOT away
    sentinel = c["outdoor_temp_c"] < -60
    quality["context_outdoor_sentinel_to_unknown"] = int(sentinel.sum())
    c.loc[sentinel, "outdoor_temp_c"] = np.nan
    c = c.drop_duplicates(subset=["flat_id", "timestamp_utc"], keep="first")
    return _in_period(c[["flat_id", "timestamp_utc", "occupants_home", "indoor_temp_c", "outdoor_temp_c"]])


def _load_long(path, quality: dict) -> pd.DataFrame:
    r = pd.read_csv(path, dtype={"flat_id": str, "appliance_id": str})
    r["timestamp_utc"] = parse_utc(r["timestamp_utc"].astype(str))
    r["kwh"] = pd.to_numeric(r["kwh"], errors="coerce")                        # NaN = missing, never 0
    if "channel" not in r.columns:
        r["channel"] = r["appliance_id"].str.split("-").str[-1]
    n = len(r)
    r = r.drop_duplicates(subset=["appliance_id", "timestamp_utc"], keep="first")
    quality["readings_duplicate_keys_dropped"] = n - len(r)
    quality["readings_missing_kwh"] = int(r["kwh"].isna().sum())
    return _in_period(r[["flat_id", "appliance_id", "channel", "timestamp_utc", "kwh"]]).reset_index(drop=True)


def _from_table(path, quality: dict):
    t = pd.read_csv(path)
    readings = t.rename(columns={"appliance_code": "channel", "energy_kwh": "kwh"})[["flat_id", "channel", "hour_idx", "kwh"]]
    hh = t.drop_duplicates(["flat_id", "hour_idx"])
    context = hh[["flat_id", "hour_idx", "occupants_home", "outdoor_temp_c"]]
    prices = hh.drop_duplicates("hour_idx")[["hour_idx", "spot_sek_per_kwh", "carbon_gco2e_per_kwh"]].rename(
        columns={"spot_sek_per_kwh": "spot", "carbon_gco2e_per_kwh": "carbon"})
    meta = hh.drop_duplicates("flat_id")[["flat_id", "residents", "floor_area_m2", "price_area"]].reset_index(drop=True)
    quality.update(readings_missing_kwh=int(t.energy_missing.sum()), readings_rows=len(t),
                   prices_missing_spot_hours=int(prices.spot.isna().sum()),
                   context_occupancy_missing=int(context.occupants_home.isna().sum()),
                   context_outdoor_missing=int(context.outdoor_temp_c.isna().sum()),
                   cleaning="analysis/clean_data.py (see reports/data_quality_report.md)")
    return flats_from_frames(readings, context, prices, meta), meta


def load() -> tuple[Dataset, dict]:
    source, path = resolve_source()
    quality: dict = {"data_source": source, "path": path}
    if source == "processed":
        flats, meta = _from_table(path, quality)
    else:
        if source == "mock" and not (C.MOCK_DIR / "clean_readings.csv").exists():
            from mock_data import generate                                   # backend/mock_data.py
            generate()
        meta = load_flats()
        readings = _load_long(C.MOCK_DIR / "clean_readings.csv" if source == "mock" else path, quality)
        prices = load_prices(quality)
        area = meta["price_area"].iloc[0]
        prices = prices[prices.price_area == area]
        flats = flats_from_frames(readings, load_context(meta, quality), prices, meta)
        quality["readings_rows"] = len(readings)
    return Dataset(flats=flats, meta=meta), quality
